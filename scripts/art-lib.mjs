import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const PNG_SIGNATURE = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];

export const nodeIo = {
  exists: (path) => existsSync(path),
  list: (dir) => readdirSync(dir),
  read: (path) => readFileSync(path),
};

/** Reads `<id>.png` files from `dir` into data URIs, in `names` order; a missing folder gives an empty manifest. */
export function buildManifest(dir, names, label, io = nodeIo) {
  if (!io.exists(dir)) return {};
  const files = io.list(dir).filter((f) => f.endsWith('.png'));
  for (const f of files) {
    if (!names.includes(f.slice(0, -4))) throw new Error(`unknown ${label}: ${f}`);
  }
  const out = {};
  for (const id of names) {
    if (!files.includes(`${id}.png`)) continue;
    const bytes = io.read(join(dir, `${id}.png`));
    if (!PNG_SIGNATURE.every((b, i) => bytes[i] === b)) throw new Error(`${id}.png is not a PNG`);
    out[id] = `data:image/png;base64,${Buffer.from(bytes).toString('base64')}`;
  }
  return out;
}

/** The generated TypeScript module text for a manifest (LF line endings, a fixed order). */
export function renderManifestModule({ script, dir, typeName, typeFrom, constName }, manifest) {
  const lines = Object.entries(manifest).map(([id, uri]) => `  ${id}: '${uri}',`);
  return [
    `// Generated by scripts/${script} from ${dir}. Do not edit by hand.`,
    '',
    `import type { ${typeName} } from '${typeFrom}';`,
    '',
    `export const ${constName}: Partial<Record<${typeName}, string>> = {`,
    ...lines,
    '};',
    '',
  ].join('\n');
}
