import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

/** The planet art ids, in drawing order (kept equal to PLANET_ART_IDS in src/screens/planetart.ts by a test). */
export const PLANET_ART_NAMES = [
  'backdrop',
  'outpost_enemy', 'outpost_taken', 'settlement_neutral', 'settlement_allied',
  'wild_a', 'wild_b', 'wild_visited', 'start_ship', 'citadel_enemy', 'citadel_taken',
  'stamp_scorch', 'stamp_cleared', 'stamp_fields',
];

const PNG_SIGNATURE = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];

const nodeIo = {
  exists: (path) => existsSync(path),
  list: (dir) => readdirSync(dir),
  read: (path) => readFileSync(path),
};

/** Reads `<id>.png` files from `dir` into data URIs, in `PLANET_ART_NAMES` order; a missing folder gives an empty manifest. */
export function buildPlanetManifest(dir, io = nodeIo) {
  if (!io.exists(dir)) return {};
  const files = io.list(dir).filter((f) => f.endsWith('.png'));
  for (const f of files) {
    if (!PLANET_ART_NAMES.includes(f.slice(0, -4))) throw new Error(`unknown planet art: ${f}`);
  }
  const out = {};
  for (const id of PLANET_ART_NAMES) {
    if (!files.includes(`${id}.png`)) continue;
    const bytes = io.read(join(dir, `${id}.png`));
    if (!PNG_SIGNATURE.every((b, i) => bytes[i] === b)) throw new Error(`${id}.png is not a PNG`);
    out[id] = `data:image/png;base64,${Buffer.from(bytes).toString('base64')}`;
  }
  return out;
}

export function renderPlanetModule(manifest) {
  const lines = Object.entries(manifest).map(([id, uri]) => `  ${id}: '${uri}',`);
  return [
    '// Generated by scripts/build-planet-art.mjs from art-src/planet. Do not edit by hand.',
    '',
    "import type { PlanetArtId } from '../screens/planetart';",
    '',
    'export const PLANET_ART_DATA: Partial<Record<PlanetArtId, string>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const manifest = buildPlanetManifest('art-src/planet');
  writeFileSync('src/art/planet.generated.ts', renderPlanetModule(manifest));
  console.log(`wrote src/art/planet.generated.ts: ${Object.keys(manifest).length} images`);
}
