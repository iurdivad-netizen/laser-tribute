import { describe, expect, it } from 'vitest';
import { CAMP_ART_NAMES, buildCampManifest, renderCampModule, type CampArtIo } from '../scripts/build-camp-art.mjs';
import { CAMP_ART_DATA } from '../src/art/camp.generated';
import { CAMP_ART_IDS } from '../src/screens/campart';

const PNG_B64 = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGNgYGD4DwABBAEAHnOcQAAAAABJRU5ErkJggg==';
const PNG = Uint8Array.from(atob(PNG_B64), (c) => c.charCodeAt(0));

function folder(files: Record<string, Uint8Array> | null): CampArtIo {
  return {
    exists: () => files !== null,
    list: () => Object.keys(files ?? {}),
    read: (path) => (files ?? {})[Object.keys(files ?? {}).find((name) => path.endsWith(name)) ?? ''],
  };
}

describe('the camp art manifest', () => {
  it('knows the same ids as the game', () => {
    expect([...CAMP_ART_NAMES]).toEqual([...CAMP_ART_IDS]);
  });

  it('turns each png into a data uri, in id order', () => {
    const m = buildCampManifest('art-src/camp', folder({ 'face_chen_s.png': PNG, 'camp_backdrop.png': PNG }));
    expect(Object.keys(m)).toEqual(['camp_backdrop', 'face_chen_s']);
    expect(m.camp_backdrop).toBe(`data:image/png;base64,${PNG_B64}`);
  });

  it('refuses an unknown file name and a file that is not a png', () => {
    expect(() => buildCampManifest('d', folder({ 'unknown.png': PNG }))).toThrow('unknown camp art');
    expect(() => buildCampManifest('d', folder({ 'market.png': Uint8Array.of(1, 2, 3, 4, 5, 6, 7, 8) }))).toThrow('not a PNG');
  });

  it('gives an empty manifest for an empty or missing folder', () => {
    expect(buildCampManifest('d', folder({}))).toEqual({});
    expect(buildCampManifest('d', folder(null))).toEqual({});
  });

  it('renders the same text whatever order the files are listed in, with the generated header', () => {
    const a = renderCampModule(buildCampManifest('d', folder({ 'camp_backdrop.png': PNG, 'market.png': PNG, 'face_dubois.png': PNG })));
    const b = renderCampModule(buildCampManifest('d', folder({ 'face_dubois.png': PNG, 'market.png': PNG, 'camp_backdrop.png': PNG })));
    expect(a).toBe(b);
    expect(a).not.toContain('\r');
    expect(a.startsWith('// Generated by scripts/build-camp-art.mjs')).toBe(true);
    expect(a).toContain('export const CAMP_ART_DATA');
  });

  it('is what is committed: the baked data equals the png files in art-src/camp', () => {
    const files = import.meta.glob('../art-src/camp/*.png', { query: '?inline', import: 'default', eager: true }) as Record<string, string>;
    const fromFiles: Record<string, string> = {};
    for (const id of CAMP_ART_NAMES) {
      const uri = files[`../art-src/camp/${id}.png`];
      if (uri) fromFiles[id] = uri;
    }
    expect(CAMP_ART_DATA).toEqual(fromFiles);
  });
});
