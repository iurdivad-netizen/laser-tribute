import { describe, expect, it } from 'vitest';
import { PLANET_ART_NAMES, buildPlanetManifest, renderPlanetModule, type PlanetArtIo } from '../scripts/build-planet-art.mjs';
import { PLANET_ART_DATA } from '../src/art/planet.generated';
import { PLANET_ART_IDS } from '../src/screens/planetart';

const PNG_B64 = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGNgYGD4DwABBAEAHnOcQAAAAABJRU5ErkJggg==';
const bytesOf = (b64: string): Uint8Array => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
const PNG = bytesOf(PNG_B64);

/** An in-memory folder: file name to bytes (no disk, so the tests need no node types). */
function folder(files: Record<string, Uint8Array> | null): PlanetArtIo {
  return {
    exists: () => files !== null,
    list: () => Object.keys(files ?? {}),
    read: (path) => (files ?? {})[Object.keys(files ?? {}).find((name) => path.endsWith(name)) ?? ''],
  };
}

describe('the planet art manifest', () => {
  it('knows the same ids as the game', () => {
    expect([...PLANET_ART_NAMES]).toEqual([...PLANET_ART_IDS]);
  });

  it('turns each png into a data uri, in stable order', () => {
    const io = folder({ 'stamp_scorch.png': PNG, 'backdrop.png': PNG });
    const m = buildPlanetManifest('art-src/planet', io);
    expect(Object.keys(m)).toEqual(['backdrop', 'stamp_scorch']);
    expect(m.backdrop).toBe(`data:image/png;base64,${PNG_B64}`);
    expect(buildPlanetManifest('art-src/planet', io)).toEqual(m);
  });

  it('refuses an unknown file name and a file that is not a png', () => {
    expect(() => buildPlanetManifest('d', folder({ 'unknown.png': PNG }))).toThrow('unknown planet art');
    expect(() => buildPlanetManifest('d', folder({ 'wild_a.png': Uint8Array.of(1, 2, 3, 4, 5, 6, 7, 8) }))).toThrow('not a PNG');
  });

  it('gives an empty manifest for an empty or missing folder', () => {
    expect(buildPlanetManifest('d', folder({}))).toEqual({});
    expect(buildPlanetManifest('d', folder(null))).toEqual({});
  });

  it('renders the same module text every time, with the generated header', () => {
    const m = buildPlanetManifest('d', folder({ 'backdrop.png': PNG }));
    const text = renderPlanetModule(m);
    expect(text).toBe(renderPlanetModule(m));
    expect(text.startsWith('// Generated by scripts/build-planet-art.mjs')).toBe(true);
    expect(text).toContain('export const PLANET_ART_DATA');
    expect(text).toContain(`backdrop: 'data:image/png;base64,${PNG_B64}'`);
  });

  it('is what is committed: the baked data equals the png files in art-src/planet', () => {
    const files = import.meta.glob('../art-src/planet/*.png', { query: '?inline', import: 'default', eager: true }) as Record<string, string>;
    const fromFiles: Record<string, string> = {};
    for (const id of PLANET_ART_NAMES) {
      const uri = files[`../art-src/planet/${id}.png`];
      if (uri) fromFiles[id] = uri;
    }
    expect(PLANET_ART_DATA).toEqual(fromFiles);
  });
});
